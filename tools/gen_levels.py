# ---------------------------------------------------------------- úseky map
def pattern(text):
    """Převede textový blok na 14 řádků mapy ('.' = prázdno)."""
    rows = [line for line in text.strip('\n').split('\n')]
    if len(rows) != HEIGHT:
        raise ValueError(f'úsek musí mít {HEIGHT} řádků, má {len(rows)}')
    width = max(len(r) for r in rows)
    return [r.ljust(width, '.').replace('.', ' ') for r in rows]


