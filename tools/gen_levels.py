def build(plan):
    """Slepí úseky vedle sebe do jedné mapy."""
    rows = [''] * HEIGHT
    for name in plan:
        part = PATTERNS[name]
        for y in range(HEIGHT):
            rows[y] += part[y]
    # Řádky necháváme stejně dlouhé, ať je mapa ve zdrojáku čitelná jako obrázek
    width = max(len(r) for r in rows)
    return [r.ljust(width) for r in rows]


# ------------------------------------------------------------------ simulace
class Map:
    """Rozparsovaná mapa – stejná pravidla jako js/level.js."""

    def __init__(self, rows):
        self.rows = rows
        self.height = len(rows)
        self.width = max(len(r) for r in rows)
        self.spawn = (1, self.height - 3)
        self.finish_x = self.width
        self.solid = set()
        self.hazard = {}
        self.trigger = {}
        self.saws = []
        self.orbiters = []
        self.rings = []

        for y, row in enumerate(rows):
            for x in range(self.width):
                ch = row[x] if x < len(row) else ' '
                if ch == '#':
                    self.solid.add((x, y))
                elif ch == '^':
                    self.hazard[(x, y)] = 'up'
                elif ch == 'v':
                    self.hazard[(x, y)] = 'down'
                elif ch == 'S':
                    self.saws.append((x + 0.5, y + 0.5))
                elif ch == '@':
                    self.orbiters.append((x + 0.5, y + 0.5))
                elif ch == 'J':
                    self.trigger[(x, y)] = 'pad'
                elif ch == 'o':
                    self.trigger[(x, y)] = 'ring'
                    self.rings.append((x, y))
                elif ch == 'D':
                    self.trigger[(x, y)] = 'gravityDown'
                elif ch == 'U':
                    self.trigger[(x, y)] = 'gravityUp'
                elif ch == 'P':
                    self.spawn = (x, y)
                elif ch == 'F':
                    self.finish_x = x

    def is_solid(self, x, y):
        return (x, y) in self.solid


def overlaps_solid(m, x, y):
    half = CUBE / 2
    for ty in range(math.floor(y - half + EPS), math.floor(y + half - EPS) + 1):
        for tx in range(math.floor(x - half + EPS), math.floor(x + half - EPS) + 1):
            if m.is_solid(tx, ty):
                return True
    return False


def box_overlap(x, y, size, bx0, by0, bx1, by1):
    half = size / 2
    return x - half < bx1 and x + half > bx0 and y - half < by1 and y + half > by0


def nearby(x, y):
    for ty in range(math.floor(y - 1), math.floor(y + 1) + 1):
        for tx in range(math.floor(x - 1), math.floor(x + 1) + 1):
            yield tx, ty


def advance(state, press, m, speed, dt):
    """Jeden snímek hry. Vrátí nový stav, None (smrt), nebo 'win'."""
    x, y, vy, grav, on_ground, rings = state

    if press:
        if on_ground:
            vy = -grav * JUMP_SPEED
            on_ground = False
        else:
            for tx, ty in nearby(x, y):
                if (m.trigger.get((tx, ty)) == 'ring' and (tx, ty) not in rings
                        and box_overlap(x, y, CUBE, tx, ty, tx + 1, ty + 1)):
                    rings = rings | {(tx, ty)}
                    vy = -grav * JUMP_SPEED
                    on_ground = False
                    break

    # --- Player.step ---
    fastest = max(speed, abs(vy), 1.0)
    steps = max(1, math.ceil(fastest * dt / MAX_SUBSTEP))
    h = dt / steps
    half = CUBE / 2

    for _ in range(steps):
        vy = max(-MAX_FALL, min(MAX_FALL, vy + grav * GRAVITY * h))

        x += speed * h
        if overlaps_solid(m, x, y):
            return None  # náraz do zdi

        y += vy * h
        on_ground = False
        if overlaps_solid(m, x, y):
            if vy > 0:
                y = math.floor(y + half) - half
                on_ground = grav > 0
            elif vy < 0:
                y = math.floor(y - half) + 1 + half
                on_ground = grav < 0
            vy = 0.0

    # --- Game.update ---
    if y > m.height + 2 or y < -3:
        return None

    for tx, ty in nearby(x, y):
        trig = m.trigger.get((tx, ty))
        if not trig or not box_overlap(x, y, CUBE, tx, ty, tx + 1, ty + 1):
            continue
        if trig == 'pad':
            vy = -grav * JUMP_SPEED * PAD_BOOST
            on_ground = False
        elif trig == 'gravityDown':
            grav = 1
        elif trig == 'gravityUp':
            grav = -1

    for tx, ty in nearby(x, y):
        hz = m.hazard.get((tx, ty))
        if hz == 'up' and box_overlap(x, y, HIT, tx + 0.22, ty + 0.35, tx + 0.78, ty + 1):
            return None
        if hz == 'down' and box_overlap(x, y, HIT, tx + 0.22, ty, tx + 0.78, ty + 0.65):
            return None

    def hits(cx, cy, radius):
        dx = max(abs(cx - x) - HIT / 2, 0)
        dy = max(abs(cy - y) - HIT / 2, 0)
        return dx * dx + dy * dy < radius * radius

    for sx, sy in m.saws:
        if hits(sx, sy, SAW_HIT):
            return None

    # Koule obíhá kolem kotvy; kostka běží konstantní rychlostí, takže odehraný
    # čas jde spočítat z její x-ové souřadnice (stejně jako `animPhase` ve hře)
    if m.orbiters:
        angle = (x - (m.spawn[0] + 0.5)) / speed * ORBIT_SPEED
        for ax, ay in m.orbiters:
            if hits(ax + math.cos(angle) * ORBIT_RADIUS,
                    ay + math.sin(angle) * ORBIT_RADIUS, BALL_HIT):
                return None

    if x >= m.finish_x:
        return 'win'

    # Prstence, které kostka minula, už nikdy nepoužije (spustí se jen při
    # překryvu). Zapomenout je není zjednodušení modelu, ale úspora: jinak
    # prohledávání drží zvlášť každou kombinaci využitých prstenců za sebou
    # a u levelu s několika prstenci roste počet stavů exponenciálně.
    rings = frozenset(r for r in rings if r[0] >= x - 2)

    return (x, y, vy, grav, on_ground, rings)


def solve(rows, speed_pct, dt, press_grid=1, limit=200000):
    """Prohledá všechny možnosti skákání. Vrátí seznam čísel snímků, ve kterých
    stačí skočit, aby se level doběhl do cíle – nebo None, když to nejde.

    `press_grid` omezí stisky jen na každý n-tý snímek – slouží jako test
    hratelnosti: level, který vyžaduje přesnost lepší než ~1/30 s, je nefér.
    """
    m = Map(rows)
    speed = BASE_SPEED * speed_pct / 100
    start = (m.spawn[0] + 0.5, m.spawn[1] + 0.5, 0.0, 1, False, frozenset())
    frontier = [start]
    history = []  # historie[snímek] = [(stav, index rodiče, skok?)]
    frames = int(m.width / (speed * dt)) + 600

    def path_to(frame, parent, press):
        """Poskládá zpětně seznam snímků, ve kterých se skákalo."""
        jumps = [frame] if press else []
        idx = parent
        for f in range(frame - 1, -1, -1):
            _, idx, pressed = history[f][idx]
            if pressed:
                jumps.append(f)
        return list(reversed(jumps))

    for frame in range(frames):
        entries = []
        seen = set()
        presses = (False, True) if frame % press_grid == 0 else (False,)

        for parent, st in enumerate(frontier):
            for press in presses:
                res = advance(st, press, m, speed, dt)
                if res is None:
                    continue
                if res == 'win':
                    return path_to(frame, parent, press)
                key = (round(res[1] * 128), round(res[2] * 64), res[3], res[4], res[5])
                if key in seen:
                    continue
                seen.add(key)
                entries.append((res, parent, press))

        if not entries:
            return None
        if len(entries) > limit:
            entries = entries[:limit]
        history.append(entries)
        frontier = [e[0] for e in entries]

    return None


