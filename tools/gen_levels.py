def build(plan):
    """Slepí úseky vedle sebe do jedné mapy."""
    rows = [''] * HEIGHT
    for name in plan:
        part = PATTERNS[name]
        for y in range(HEIGHT):
            rows[y] += part[y]
    # Řádky necháváme stejně dlouhé, ať je mapa ve zdrojáku čitelná jako obrázek
    width = max(len(r) for r in rows)
    return [r.ljust(width) for r in rows]


